"""Arms for the 90-240 s sweep on the 07:00-09:00 cells (task w07x, 2026-10-01).

New arms: C-<x>, Mplus-<x> for x in 90, 150, 180, 240 s and V-<x> for x in 90, 120, 150, 180, 240 s.
Derivation = make_configs_t3.arm() (same base, same edits), re-stated here instead of imported, because importing
make_configs_t3 rewrites its 13 files at import. To show the re-statement is the same derivation, every existing arm
file in ../configs/ (U, C-30..900, Mplus-30..900, V-30/60/120, M-30/60/120) is regenerated in memory and must be
byte-identical; nothing in ../configs/ is written. New files go to ./configs/ with exclusive create (never overwrite).
The log proves: each C-x / Mplus-x pair differs in exactly the two intended keys; each V-x differs from C-x only in
budgetBasis; the V-120 written here equals ../configs/V-120.json.
Usage: python -B make_configs_w07x.py > make_configs_w07x.log   (run once)
"""
import copy
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OLD = HERE.parent / "configs"
NEW = HERE / "configs"
BASE = Path(r"E:/Code/RideBound-deadline/benchmarks/configurations/wp14-c1-h6-reference-v1.json")
POLICY_ID = "wp6-synthetic-policy-overlay-v1"
base_bytes = BASE.read_bytes()
base = json.loads(base_bytes)
assert [p["policyId"] for p in base["policies"]] == [POLICY_ID]


def leaves(value, prefix=""):  # same as make_configs_t3.leaves
    if isinstance(value, dict):
        for key, sub in value.items():
            yield from leaves(sub, f"{prefix}.{key}")
    elif isinstance(value, list):
        if value and isinstance(value[0], dict) and "dimension" in value[0]:
            for sub in value:
                yield from leaves(sub, f"{prefix}[{sub['dimension']}]")
        elif value and isinstance(value[0], dict):
            for index, sub in enumerate(value):
                yield from leaves(sub, f"{prefix}[{index}]")
        else:
            yield prefix, json.dumps(value, sort_keys=True)
    else:
        yield prefix, json.dumps(value)


def diff(a, b):
    la, lb = dict(leaves(a)), dict(leaves(b))
    return sorted((k, la.get(k, "<absent>"), lb.get(k, "<absent>")) for k in set(la) | set(lb) if la.get(k) != lb.get(k))


def arm(basis=None, cap_s=None, slack_s=None, two_sided=False):  # same edits as make_configs_t3.arm
    config = copy.deepcopy(base)
    policy = config["policies"][0]
    found = [limit for limit in policy["limits"] if limit["dimension"] == "drop_eta_total_ms"]
    assert len(found) == 1 and found[0]["hardLimit"] == 30000
    if cap_s is None:
        del found[0]["hardLimit"]
    else:
        found[0]["hardLimit"] = cap_s * 1000
    if basis is not None:
        policy["budgetBasis"] = basis
    if slack_s is not None:
        policy["dropEtaDeadlineSlackMs"] = slack_s * 1000
        if two_sided:
            policy["dropEtaDeadlineTwoSided"] = True
    return config


def encode(name, data):
    if name == "C-30":
        assert data == base
        return base_bytes
    return (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main() -> int:
    problems = []
    print("base sha256:", hashlib.sha256(base_bytes).hexdigest())
    existing = {"U": arm()}
    for x in (30, 60, 120, 300, 600, 900):
        existing[f"C-{x}"] = arm(cap_s=x)
        existing[f"Mplus-{x}"] = arm(slack_s=x)
    for x in (30, 60, 120):
        existing[f"V-{x}"] = arm(basis="customerVisible", cap_s=x)
        existing[f"M-{x}"] = arm(slack_s=x, two_sided=True)
    for name, data in sorted(existing.items()):
        on_disk = (OLD / f"{name}.json").read_bytes()
        same = encode(name, data) == on_disk
        print(f"existing {name}: regenerated bytes identical to ../configs/{name}.json: {same} "
              f"(sha256 {hashlib.sha256(on_disk).hexdigest()})")
        if not same:
            problems.append(f"re-stated derivation differs for existing {name}")
    new = {}
    for x in (90, 150, 180, 240):
        new[f"C-{x}"] = arm(cap_s=x)
        new[f"Mplus-{x}"] = arm(slack_s=x)
    for x in (90, 120, 150, 180, 240):
        new[f"V-{x}"] = arm(basis="customerVisible", cap_s=x)
    NEW.mkdir(exist_ok=True)
    for name, data in sorted(new.items()):
        content = encode(name, data)
        with open(NEW / f"{name}.json", "xb") as handle:
            handle.write(content)
        print(f"new {name}: {hashlib.sha256(content).hexdigest()}")
        for key, old, value in diff(base, data):
            print(f"    {name} differs from base at {key}: {old} -> {value}")
    for x in (90, 150, 180, 240):
        keys = sorted(k for k, _, _ in diff(new[f"C-{x}"], new[f"Mplus-{x}"]))
        ok = keys == [".policies[0].dropEtaDeadlineSlackMs", ".policies[0].limits[drop_eta_total_ms].hardLimit"]
        print(f"C-{x} vs Mplus-{x}: differs at {keys} -> {'OK' if ok else 'PROBLEM'}")
        if not ok:
            problems.append(f"C-{x}/Mplus-{x} differ at {keys}")
    for x in (90, 120, 150, 180, 240):
        c = new.get(f"C-{x}", existing.get(f"C-{x}"))
        pairs = diff(c, new[f"V-{x}"])
        ok = [k for k, _, _ in pairs] == [".policies[0].budgetBasis"]
        print(f"C-{x} vs V-{x}: {pairs} -> {'OK' if ok else 'PROBLEM'}")
        if not ok:
            problems.append(f"C-{x}/V-{x} differ at {pairs}")
    same_v120 = (NEW / "V-120.json").read_bytes() == (OLD / "V-120.json").read_bytes()
    print(f"new V-120 equals ../configs/V-120.json: {same_v120}")
    if not same_v120:
        problems.append("V-120 differs from ../configs/V-120.json")
    print("problems:", problems or "none")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
